#!/usr/bin/env bash
# Quick validation for weight ~= 10GiB with reduced runtime decision overhead.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

RUN_ROOT="${RUN_ROOT:-log/stage_m_active_experts_residency_weight10g_quiet_run}"
LOG_FILE="${LOG_FILE:-log/stage_m_active_experts_residency_weight10g_quiet.log}"
PROMPTS="${PROMPTS:-1}"
OUTPUT_LEN="${OUTPUT_LEN:-16}"
WEIGHT_EXECUTOR="${WEIGHT_EXECUTOR:-driver_batch}"

WEIGHT_GPU_BYTES="${WEIGHT_GPU_BYTES:-10737418240}"   # 10 GiB
KV_GPU_BYTES="${KV_GPU_BYTES:-2147483648}"            # 2 GiB
HOT_EXPERTS_PER_LAYER="${HOT_EXPERTS_PER_LAYER:-48}"
COLD_EXPERTS_PER_LAYER="${COLD_EXPERTS_PER_LAYER:-80}"
ACTIVE_EXPERTS_PER_LAYER="${ACTIVE_EXPERTS_PER_LAYER:-32}"

WEIGHT_ACTIVE_EVICT_MAX_EXPERTS_PER_LAYER="${WEIGHT_ACTIVE_EVICT_MAX_EXPERTS_PER_LAYER:-16}"
WEIGHT_MAX_VICTIMS_PER_STEP="${WEIGHT_MAX_VICTIMS_PER_STEP:-16}"
WEIGHT_PREFETCH_MAX_BYTES_PER_STEP="${WEIGHT_PREFETCH_MAX_BYTES_PER_STEP:-268435456}"

# Low-overhead knobs
WEIGHT_PREFETCH_TRACE_ENABLE="${WEIGHT_PREFETCH_TRACE_ENABLE:-0}"
WEIGHT_ROUTER_TOPK_EVERY_N_STEPS="${WEIGHT_ROUTER_TOPK_EVERY_N_STEPS:-4}"
POOL_COORDINATOR_TRACE_ENABLE="${POOL_COORDINATOR_TRACE_ENABLE:-0}"

REAL_ON_REGISTER_EVERY="${REAL_ON_REGISTER_EVERY:-8192}"
REAL_ON_ACTION_EVERY="${REAL_ON_ACTION_EVERY:-1024}"
REAL_MAX_SNAPSHOTS="${REAL_MAX_SNAPSHOTS:-16}"

echo "Stage M active-experts residency 10G quiet experiment"
echo "Run root: $RUN_ROOT"
echo "Log file: $LOG_FILE"
echo "Weight GPU budget: $WEIGHT_GPU_BYTES"
echo "KV GPU budget: $KV_GPU_BYTES"
echo "Hot/cold plan: hot=$HOT_EXPERTS_PER_LAYER cold=$COLD_EXPERTS_PER_LAYER"
echo "Active experts/layer target: $ACTIVE_EXPERTS_PER_LAYER"
echo "Prefetch trace: $WEIGHT_PREFETCH_TRACE_ENABLE"
echo "Router topk every N steps: $WEIGHT_ROUTER_TOPK_EVERY_N_STEPS"
echo "Coordinator trace: $POOL_COORDINATOR_TRACE_ENABLE"

VLLM_UVM_PHASE_F_IOCTL_MODE="${VLLM_UVM_PHASE_F_IOCTL_MODE:-policy}" \
UVM_PHASE_F_ROUTE_LOG_DELAY_MS="${UVM_PHASE_F_ROUTE_LOG_DELAY_MS:-0}" \
HOT_EXPERTS_PER_LAYER="$HOT_EXPERTS_PER_LAYER" \
COLD_EXPERTS_PER_LAYER="$COLD_EXPERTS_PER_LAYER" \
ACTIVE_EXPERTS_PER_LAYER="$ACTIVE_EXPERTS_PER_LAYER" \
WEIGHT_ACTIVE_EVICT_MAX_EXPERTS_PER_LAYER="$WEIGHT_ACTIVE_EVICT_MAX_EXPERTS_PER_LAYER" \
WEIGHT_MAX_VICTIMS_PER_STEP="$WEIGHT_MAX_VICTIMS_PER_STEP" \
WEIGHT_PREFETCH_MAX_BYTES_PER_STEP="$WEIGHT_PREFETCH_MAX_BYTES_PER_STEP" \
WEIGHT_GPU_BYTES="$WEIGHT_GPU_BYTES" \
KV_GPU_BYTES="$KV_GPU_BYTES" \
WEIGHT_PREFETCH_TRACE_ENABLE="$WEIGHT_PREFETCH_TRACE_ENABLE" \
WEIGHT_ROUTER_TOPK_EVERY_N_STEPS="$WEIGHT_ROUTER_TOPK_EVERY_N_STEPS" \
POOL_COORDINATOR_TRACE_ENABLE="$POOL_COORDINATOR_TRACE_ENABLE" \
REAL_ON_REGISTER_EVERY="$REAL_ON_REGISTER_EVERY" \
REAL_ON_ACTION_EVERY="$REAL_ON_ACTION_EVERY" \
REAL_MAX_SNAPSHOTS="$REAL_MAX_SNAPSHOTS" \
PROMPTS="$PROMPTS" \
OUTPUT_LEN="$OUTPUT_LEN" \
"$SCRIPT_DIR/run_stage_m_active_experts_residency.sh" \
  --run-root "$RUN_ROOT" \
  --log-file "$LOG_FILE" \
  --server-max-num-seqs 1 \
  --request-rate 1 \
  --prompts "$PROMPTS" \
  --output-len "$OUTPUT_LEN" \
  --weight-executor "$WEIGHT_EXECUTOR"

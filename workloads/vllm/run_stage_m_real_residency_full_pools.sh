#!/usr/bin/env bash
# Measure page-granular real UVM residency for all pools currently registered
# by the vLLM UVM policy stack: MoE weights, KV cache, and scratch.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

RUN_ROOT="${RUN_ROOT:-log/stage_m_real_residency_full_pools_run}"
LOG_FILE="${LOG_FILE:-log/stage_m_real_residency_full_pools.log}"
PROMPTS="${PROMPTS:-1}"
OUTPUT_LEN="${OUTPUT_LEN:-32}"
WEIGHT_EXECUTOR="${WEIGHT_EXECUTOR:-driver_batch}"

# Current weight registry covers MoE expert tensors. Use hot+cold=128 to cover
# all experts/layer while still producing a cold offload plan for driver_batch
# validation. Dense/attention weights require additional registry coverage
# before they can appear in this report.
HOT_EXPERTS_PER_LAYER="${HOT_EXPERTS_PER_LAYER:-64}"
COLD_EXPERTS_PER_LAYER="${COLD_EXPERTS_PER_LAYER:-64}"

# Keep runtime prefetch off by default because earlier ablations showed it can
# dominate latency. Set WEIGHT_RUNTIME_PREFETCH_ENABLE=1 to measure that path.
WEIGHT_RUNTIME_PREFETCH_ENABLE="${WEIGHT_RUNTIME_PREFETCH_ENABLE:-0}"

INIT_WEIGHT_OFFLOAD_ENABLE="${INIT_WEIGHT_OFFLOAD_ENABLE:-1}"
SCRATCH_DEVICE_DIRECT_ENABLE="${SCRATCH_DEVICE_DIRECT_ENABLE:-1}"
SCRATCH_POOL_ENABLE="${SCRATCH_POOL_ENABLE:-1}"
RESIDENCY_ENABLE="${RESIDENCY_ENABLE:-1}"
RESIDENCY_TRACE_ENABLE="${RESIDENCY_TRACE_ENABLE:-1}"
KV_RUNTIME_ENABLE="${KV_RUNTIME_ENABLE:-1}"
POOL_COORDINATOR_ENABLE="${POOL_COORDINATOR_ENABLE:-1}"
POOL_REGISTRY_ENABLE="${POOL_REGISTRY_ENABLE:-1}"
AUTO_GAP_WATCH_ENABLE="${AUTO_GAP_WATCH_ENABLE:-1}"
FAULT_ADDRESS_LOG_ENABLE="${FAULT_ADDRESS_LOG_ENABLE:-1}"

REAL_ON_REGISTER_EVERY="${REAL_ON_REGISTER_EVERY:-2048}"
REAL_ON_ACTION_EVERY="${REAL_ON_ACTION_EVERY:-64}"
REAL_MAX_SNAPSHOTS="${REAL_MAX_SNAPSHOTS:-24}"
REAL_MAX_REGIONS_PER_POOL="${REAL_MAX_REGIONS_PER_POOL:-0}"

echo "Stage M real residency full-pools experiment"
echo "Run root: $RUN_ROOT"
echo "Log file: $LOG_FILE"
echo "MoE registry plan: hot=$HOT_EXPERTS_PER_LAYER cold=$COLD_EXPERTS_PER_LAYER"
echo "Runtime prefetch: $WEIGHT_RUNTIME_PREFETCH_ENABLE"

INIT_WEIGHT_OFFLOAD_ENABLE="$INIT_WEIGHT_OFFLOAD_ENABLE" \
WEIGHT_RUNTIME_PREFETCH_ENABLE="$WEIGHT_RUNTIME_PREFETCH_ENABLE" \
SCRATCH_DEVICE_DIRECT_ENABLE="$SCRATCH_DEVICE_DIRECT_ENABLE" \
SCRATCH_POOL_ENABLE="$SCRATCH_POOL_ENABLE" \
RESIDENCY_ENABLE="$RESIDENCY_ENABLE" \
RESIDENCY_TRACE_ENABLE="$RESIDENCY_TRACE_ENABLE" \
KV_RUNTIME_ENABLE="$KV_RUNTIME_ENABLE" \
POOL_COORDINATOR_ENABLE="$POOL_COORDINATOR_ENABLE" \
POOL_REGISTRY_ENABLE="$POOL_REGISTRY_ENABLE" \
AUTO_GAP_WATCH_ENABLE="$AUTO_GAP_WATCH_ENABLE" \
FAULT_ADDRESS_LOG_ENABLE="$FAULT_ADDRESS_LOG_ENABLE" \
REAL_ON_REGISTER_EVERY="$REAL_ON_REGISTER_EVERY" \
REAL_ON_ACTION_EVERY="$REAL_ON_ACTION_EVERY" \
REAL_MAX_SNAPSHOTS="$REAL_MAX_SNAPSHOTS" \
REAL_MAX_REGIONS_PER_POOL="$REAL_MAX_REGIONS_PER_POOL" \
"$SCRIPT_DIR/run_stage_m_real_residency_check.sh" \
  --run-root "$RUN_ROOT" \
  --log-file "$LOG_FILE" \
  --prompts "$PROMPTS" \
  --output-len "$OUTPUT_LEN" \
  --weight-executor "$WEIGHT_EXECUTOR" \
  --init-weight-offload-enable "$INIT_WEIGHT_OFFLOAD_ENABLE" \
  --weight-runtime-prefetch-enable "$WEIGHT_RUNTIME_PREFETCH_ENABLE" \
  --hot-experts-per-layer "$HOT_EXPERTS_PER_LAYER" \
  --cold-experts-per-layer "$COLD_EXPERTS_PER_LAYER" \
  "$@"

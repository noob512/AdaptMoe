#!/usr/bin/env bash
# Stage N hard-partition proof experiment.
#
# This wrapper runs the enforce probe with strict acceptance. A run only passes
# if every pool is under budget at the final driver state, or the run contains
# pool-specific deny/block evidence for any over-budget pool.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

RUN_ROOT="${RUN_ROOT:-log/stage_n_hard_partition_proof_$(date -u +%Y%m%d_%H%M%S)}"

MODEL="${MODEL:-Qwen/Qwen3-30B-A3B-FP8}"
REPEATS="${REPEATS:-2}"
PROMPTS="${PROMPTS:-8}"
REQUEST_RATE="${REQUEST_RATE:-2}"
OUTPUT_LEN="${OUTPUT_LEN:-32}"
MAX_MODEL_LEN="${MAX_MODEL_LEN:-2048}"
SERVER_MAX_NUM_SEQS="${SERVER_MAX_NUM_SEQS:-4}"
SERVER_GPU_MEMORY_UTILIZATION="${SERVER_GPU_MEMORY_UTILIZATION:-0.70}"
STARTUP_TIMEOUT="${STARTUP_TIMEOUT:-1800}"
PORT_BASE="${PORT_BASE:-8100}"

KV_BUDGET_BYTES="${KV_BUDGET_BYTES:-10737418240}"
ENFORCE_WEIGHT_BUDGET_BYTES="${ENFORCE_WEIGHT_BUDGET_BYTES:-21474836480}"
ENFORCE_SCRATCH_BUDGET_BYTES="${ENFORCE_SCRATCH_BUDGET_BYTES:-104857600}"
HARD_PARTITION_TOLERANCE_BYTES="${HARD_PARTITION_TOLERANCE_BYTES:-0}"

RESET_COUNTERS="${RESET_COUNTERS:-1}"
UVM_PHASE_F_ROUTE_LOG_DELAY_MS="${UVM_PHASE_F_ROUTE_LOG_DELAY_MS:-0}"

# For proof, force a scan at every sampled outer hook, try enough victims to
# cover multi-GB weight overage, and avoid hiding residual over-budget state
# behind success cooldown.
UVM_PHASE_N_AUTO_RECLAIM_EVERY="${UVM_PHASE_N_AUTO_RECLAIM_EVERY:-1}"
UVM_PHASE_N_ENFORCE_RECLAIM_EVERY="${UVM_PHASE_N_ENFORCE_RECLAIM_EVERY:-1}"
UVM_PHASE_N_ENFORCE_RECLAIM_SCAN_EVERY="${UVM_PHASE_N_ENFORCE_RECLAIM_SCAN_EVERY:-0}"
UVM_PHASE_N_ENFORCE_RECLAIM_MAX_VICTIMS="${UVM_PHASE_N_ENFORCE_RECLAIM_MAX_VICTIMS:-128}"
UVM_PHASE_N_ENFORCE_RECLAIM_COOLDOWN_EPOCHS="${UVM_PHASE_N_ENFORCE_RECLAIM_COOLDOWN_EPOCHS:-0}"
UVM_PHASE_N_AUTO_RECLAIM_FAILURE_BACKOFF_EPOCHS="${UVM_PHASE_N_AUTO_RECLAIM_FAILURE_BACKOFF_EPOCHS:-0}"
UVM_PHASE_N_ENFORCE_RECLAIM_FAILURE_BACKOFF_EPOCHS="${UVM_PHASE_N_ENFORCE_RECLAIM_FAILURE_BACKOFF_EPOCHS:-0}"
UVM_PHASE_N_ENFORCE_RECLAIM_EXECUTE_ON_READY="${UVM_PHASE_N_ENFORCE_RECLAIM_EXECUTE_ON_READY:-1}"
VLLM_UVM_DRIVER_SCRATCH_BUDGET_ENFORCE_WARMUP="${VLLM_UVM_DRIVER_SCRATCH_BUDGET_ENFORCE_WARMUP:-0}"

export RUN_ROOT
export MODEL
export P7_VARIANTS=stage_n_enforce_probe
export REPEATS
export PROMPTS
export REQUEST_RATE
export OUTPUT_LEN
export MAX_MODEL_LEN
export SERVER_MAX_NUM_SEQS
export SERVER_GPU_MEMORY_UTILIZATION
export STARTUP_TIMEOUT
export PORT_BASE
export KV_BUDGET_BYTES
export ENFORCE_WEIGHT_BUDGET_BYTES
export ENFORCE_SCRATCH_BUDGET_BYTES
export HARD_PARTITION_TOLERANCE_BYTES
export REQUIRE_STAGE_N_HARD_PARTITION=1
export FAIL_ON_WARN=1
export RESET_COUNTERS
export UVM_PHASE_F_ROUTE_LOG_DELAY_MS
export UVM_PHASE_N_AUTO_RECLAIM_EVERY
export UVM_PHASE_N_ENFORCE_RECLAIM_EVERY
export UVM_PHASE_N_ENFORCE_RECLAIM_SCAN_EVERY
export UVM_PHASE_N_ENFORCE_RECLAIM_MAX_VICTIMS
export UVM_PHASE_N_ENFORCE_RECLAIM_COOLDOWN_EPOCHS
export UVM_PHASE_N_AUTO_RECLAIM_FAILURE_BACKOFF_EPOCHS
export UVM_PHASE_N_ENFORCE_RECLAIM_FAILURE_BACKOFF_EPOCHS
export UVM_PHASE_N_ENFORCE_RECLAIM_EXECUTE_ON_READY
export VLLM_UVM_DRIVER_SCRATCH_BUDGET_ENFORCE_WARMUP

./run_stage_n_p7_ab_sweep.sh
